#!/usr/bin/env node
// Claude Code sessions -> vault markdown.
//
// A live Claude Code session is a .jsonl transcript in ~/.claude/projects/,
// and it is mostly not conversation: for a ninety-hour thread, 25.5 MB of file
// held 350 kB of things actually said — 1.4%. The rest is tool calls, tool
// results, attachments and queue bookkeeping. So this is not a format change,
// it is a seventy-fold reduction down to the part a person would read.
//
// Output matches what the nexus-ai-chat-importer plugin writes for ChatGPT and
// claude.ai exports — same frontmatter, same >[!nexus_user] / >[!nexus_agent]
// callouts — for two reasons: the notes read identically in Obsidian whatever
// they came from, and sweep.js splits chunks on exactly those markers.
//
// Nothing here talks to the archive. It writes files; the nightly sweep finds
// them because they are in the vault, like everything else.
//
// Usage:
//   node scripts/cc-export.js [--dry-run] [--include-thinking] [--all]
//
//   SESSIONS_DIR     default ~/.claude/projects
//   OUT_DIR          default ~/conversations/claude-code. Put it inside your
//                    VAULT_PATH so sweep.js finds it
//   MIN_MESSAGES     default 2 — below this a session is a mis-start, not a thread
//   MACHINE_PROMPTS  optional, JSON array or one regex per line: sessions whose FIRST user
//                    turn matches are skipped (cron wakes, bridges, tests)
//   HOOK_LINES       optional, JSON array or one regex per line: lines your hooks inject into
//                    user turns, stripped before export
//
// What it writes is the whole conversation in plain text. Keep OUT_DIR somewhere
// as private as the transcripts themselves.

const fs = require("fs");
const path = require("path");
const os = require("os");

const HOME = os.homedir();
const SESSIONS_DIR = process.env.SESSIONS_DIR || path.join(HOME, ".claude", "projects");
const OUT_DIR = process.env.OUT_DIR ||
  path.join(HOME, "conversations", "claude-code");
const MIN_MESSAGES = Number(process.env.MIN_MESSAGES || 2);

// Many sessions are not started by a person. A Discord bridge can spawn one per
// message, a timer one per autonomous wake, and tests spawn more. Their first
// "user" turn is a generated prompt, not something said. Left in, ours outnumbered
// the real conversations fifty to seven and every search surfaced machine chatter.
// Name your own openers in MACHINE_PROMPTS.
// A JSON array of strings, or one regex per line. (systemd env files can't do
// multi-line values, so there the JSON form is the one that works.)
const lines = (v) => {
  const t = String(v || "").trim();
  if (t.startsWith("[")) return JSON.parse(t);
  return t.split("\n").map((l) => l.trim()).filter(Boolean);
};
const MACHINE_PROMPTS = [
  /^\s*(plumbing|config) (test|check)/i,
  ...lines(process.env.MACHINE_PROMPTS).map((r) => new RegExp(r, "i")),
];
const isMachine = (t) => MACHINE_PROMPTS.some((re) => re.test(t.trim()));

const DRY_RUN = process.argv.includes("--dry-run");
const INCLUDE_THINKING = process.argv.includes("--include-thinking");
const ALL = process.argv.includes("--all");   // include sidechains (subagent runs)

// ── cleaning ────────────────────────────────────────────────────────────────
// A user turn as stored is not only what was typed. The harness injects the
// wake-up file, hook output, task notifications and reminders into the same
// string. Left in, every note would open with a copy of CLAUDE.md and the
// archive would return the instructions instead of the conversation.
const STRIP = [
  /<system-reminder>[\s\S]*?<\/system-reminder>/g,
  /<command-[a-z]+>[\s\S]*?<\/command-[a-z]+>/g,
  /<\/?command-[a-z]+>/g,
  /<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g,
  // The CLI wraps slash-command output in <local-command-*> tags with a boilerplate
  // caveat. It is not speech, and left in it becomes the note's title.
  /<\/?local-command-[a-z]+>/g,
  /^Caveat: The messages below were generated by the user while running local commands[^\n]*/gm,
  /<task-notification>[\s\S]*?<\/task-notification>/g,
  /^(?:UserPromptSubmit|SessionStart|PreToolUse|PostToolUse|Stop)[^\n]*hook[^\n]*$/gm,
  /^\[Current date\/time[^\]]*\][^\n]*$/gm,
  ...lines(process.env.HOOK_LINES).map((r) => new RegExp(r, "gm")),
  /^Called the \w+ tool with the following input:[\s\S]*?(?=\n\n|$)/gm,
  // On compaction the harness replays a summary of the thread as if it were a
  // user turn. It is neither of us speaking, and indexing it would return a
  // recount instead of the night itself — the exact failure the archive rework
  // was meant to end.
  /This session is being continued from a previous conversation[\s\S]*$/,
];

function clean(text) {
  let out = String(text || "");
  for (const re of STRIP) out = out.replace(re, "");
  return out.replace(/\n{3,}/g, "\n\n").trim();
}

// Content arrives either as a plain string (what was typed) or as blocks.
// Tool results and tool calls are dropped; they are the 98.6%.
function textOf(content, role) {
  if (typeof content === "string") return clean(content);
  if (!Array.isArray(content)) return "";
  const parts = [];
  for (const b of content) {
    if (!b || typeof b !== "object") continue;
    if (b.type === "text") parts.push(clean(b.text));
    else if (b.type === "image") parts.push("*(image)*");
    else if (b.type === "thinking" && INCLUDE_THINKING && role === "assistant") {
      const t = clean(b.thinking);
      if (t) parts.push(`*(thinking)*\n${t}`);
    }
  }
  return parts.filter(Boolean).join("\n\n").trim();
}

function readSession(file) {
  const msgs = [];
  let first = null, last = null, cwd = null, sessionId = null;

  for (const line of fs.readFileSync(file, "utf-8").split("\n")) {
    if (!line.trim()) continue;
    let d;
    try { d = JSON.parse(line); } catch { continue; }

    if (d.timestamp) { first = first || d.timestamp; last = d.timestamp; }
    cwd = cwd || d.cwd || null;
    sessionId = sessionId || d.sessionId || null;

    if (d.type !== "user" && d.type !== "assistant") continue;
    if (d.isSidechain && !ALL) continue;

    const role = d.type;
    const body = textOf(d.message && d.message.content, role);
    if (!body) continue;

    // Consecutive same-role turns happen constantly — one reply split across
    // several records by tool calls in between. Join them so a chunk boundary
    // never lands in the middle of one thing that was said.
    const prev = msgs[msgs.length - 1];
    if (prev && prev.role === role) prev.body += "\n\n" + body;
    else msgs.push({ role, body, at: d.timestamp || last });
  }
  return { msgs, first, last, cwd, sessionId };
}

// ── formatting ──────────────────────────────────────────────────────────────
const pad = (n) => String(n).padStart(2, "0");
function stamp(iso) {
  if (!iso) return "";
  const d = new Date(iso);
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()} at ` +
         `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

const quote = (s) => s.split("\n").map((l) => (l.trim() ? `> ${l}` : ">")).join("\n");

function titleOf(msgs) {
  const firstUser = msgs.find((m) => m.role === "user");
  if (!firstUser) return "Untitled session";
  const lines = firstUser.body.split("\n").map((l) => l.trim())
    .filter((l) => l && !l.startsWith("*") && !l.startsWith("#"));
  // A thread that opens with "*flops*" is not called flops. Prefer the first
  // line with something in it; fall back to the first line of any kind.
  const line = lines.find((l) => l.length >= 25) || lines[0] || firstUser.body.trim();
  const t = line.replace(/\s+/g, " ").slice(0, 70).trim();
  return t || "Untitled session";
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 50) || "session";

function render(session, title) {
  const { msgs, first, last, sessionId, cwd } = session;
  const fm = [
    "---",
    "nexus: cc-export",
    "provider: claude-code",
    `aliases: ${JSON.stringify(title)}`,
    `conversation_id: ${sessionId || "unknown"}`,
    `create_time: ${first || ""}`,
    `update_time: ${last || ""}`,
    cwd ? `cwd: ${cwd}` : null,
    "---",
    "",
    `# Title: ${title}`,
    "",
    `Created: ${stamp(first)}`,
    `Last Updated: ${stamp(last)}`,
    "",
    "",
  ].filter((l) => l !== null).join("\n");

  const body = msgs.map((m) => {
    const head = m.role === "user"
      ? `>[!nexus_user] **User** - ${stamp(m.at)}`
      : `>[!nexus_agent] **Assistant** - ${stamp(m.at)}`;
    return `${head}\n${quote(m.body)}`;
  }).join("\n");

  return fm + body + "\n";
}

// ── main ────────────────────────────────────────────────────────────────────
function findSessions(dir) {
  const out = [];
  (function walk(d) {
    let entries;
    try { entries = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      const full = path.join(d, e.name);
      if (e.isDirectory()) walk(full);
      else if (e.name.endsWith(".jsonl")) out.push(full);
    }
  })(dir);
  return out.sort();
}

function main() {
  const files = findSessions(SESSIONS_DIR);
  let written = 0, unchanged = 0, skipped = 0, machine = 0, bytesIn = 0, bytesOut = 0;

  for (const file of files) {
    bytesIn += fs.statSync(file).size;
    const session = readSession(file);
    if (session.msgs.length < MIN_MESSAGES) { skipped++; continue; }
    const opener = session.msgs.find((m) => m.role === "user");
    if (opener && isMachine(opener.body)) { machine++; continue; }

    const title = titleOf(session.msgs);
    const when = new Date(session.first || Date.now());
    const short = (session.sessionId || path.basename(file, ".jsonl")).slice(0, 8);
    const rel = path.join(
      String(when.getFullYear()),
      pad(when.getMonth() + 1),
      `${when.getFullYear()}-${pad(when.getMonth() + 1)}-${pad(when.getDate())}-${slug(title)}-${short}.md`
    );
    const dest = path.join(OUT_DIR, rel);
    const content = render(session, title);
    bytesOut += Buffer.byteLength(content);

    // Rewriting an identical file would churn file sync and make the sweep
    // re-embed a conversation that has not changed. Compare before writing.
    let existing = null;
    try { existing = fs.readFileSync(dest, "utf-8"); } catch {}
    if (existing === content) { unchanged++; continue; }

    if (!DRY_RUN) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, content);
    }
    written++;
    console.log(`${DRY_RUN ? "would write" : "wrote"}  ${rel}  (${session.msgs.length} messages)`);
  }

  const pct = bytesIn ? ((bytesOut / bytesIn) * 100).toFixed(1) : "0";
  console.log(
    `\ncc-export ${DRY_RUN ? "(dry run) " : ""}done: ${written} written, ${unchanged} unchanged, ` +
    `${skipped} too short, ${machine} machine-spawned. ${(bytesIn / 1e6).toFixed(1)} MB of transcript -> ` +
    `${(bytesOut / 1e6).toFixed(2)} MB of conversation (${pct}%).`
  );
}

main();
